"""Generates every skill's references/ bundle from this project's authored
source — frameworks/, rubric/, and family-manifest.yaml — per build-plan.md
§5. Nothing under a skill's references/ is hand-edited; it's regenerated by
this script, and tests/test_skill_bundle_sync.py asserts running it produces
exactly what's committed.

Two entry points, because the manifest-driven bulk sync (`sync_all`) can't
exist before family-manifest.yaml does (build sequence step 9), but a single
skill needs syncing as soon as it exists (step 6):

- `sync_skill_references` — sync one skill directory directly, given its
  domain explicitly. This is what step 6 uses for the flagship skill.
- `sync_all` — reads family-manifest.yaml and syncs every `status: built`
  entry plus the router, in one pass. This is what CI and the Makefile's
  `sync-skill-bundle` target use once the manifest exists.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import yaml

from privacy_and_ai_governance.frameworks import active_frameworks, load_framework_registry

# The src/ modules with no dependency beyond the standard library — these get
# copied byte-for-byte into a skill's scripts/, per docs/standards/skills.md's
# standalone-distribution requirement. frameworks.py (and the src/ version of
# assessment.py, which imports it) needs PyYAML and is deliberately excluded:
# a skill's own scripts/assessment.py is hand-authored to read the
# JSON-rendered framework index this script produces instead.
STDLIB_ONLY_MODULES = ["concision.py", "language.py", "report.py", "rubric.py"]


class ManifestDriftError(Exception):
    """Raised when family-manifest.yaml claims a skill is "built" but no
    matching folder exists under .claude/skills/ — build-plan.md §6.2.
    """


def render_frameworks_index_markdown(records: list[dict[str, Any]]) -> str:
    """Renders a filtered list of framework records as the Markdown a
    skill's SKILL.md instructs the model to read (build-plan.md §3, "How a
    skill actually consumes this").
    """
    lines = ["# Framework registry", ""]
    if not records:
        lines.append("No frameworks are currently registered for this domain.")
        return "\n".join(lines) + "\n"

    for record in records:
        lines.append(f"## {record['id']} — {record['name']}")
        lines.append("")
        lines.append(f"- **Type:** {record['type']}")
        lines.append(f"- **Citation root:** {record['citation_root']}")
        lines.append(f"- **Review status:** {record['review_status']}")
        lines.append(f"- **Source:** {record['source_url']}")
        lines.append(f"- **Trigger:** {record['applicability']['trigger']}")
        lines.append(f"- **Jurisdiction:** {', '.join(record['applicability']['jurisdiction'])}")
        lines.append(f"- **File:** `frameworks/{record['file']}`")
        lines.append("")
    return "\n".join(lines)


def sync_skill_references(
    skill_dir: Path,
    domain: str,
    frameworks_dir: Path,
    rubric_path: Path | None,
    baseline_path: Path | None = None,
) -> list[Path]:
    """Regenerates skill_dir/references/ for a specialist skill: a copy of
    the rubric (if *rubric_path* is given — a triage- or incident-shaped
    skill has none, per build-plan.md steps 12 and 14), a copy of the
    vendor-review baseline (if *baseline_path* is given — only a
    review-shaped skill has one, per build-plan.md step 16), a rendered
    index of every active framework in *domain*, and a copy of each such
    framework's content file. Returns every path written.
    """
    references_dir = skill_dir / "references"
    written: list[Path] = []

    if rubric_path is not None:
        rubric_dest = references_dir / "rubric" / rubric_path.name
        rubric_dest.parent.mkdir(parents=True, exist_ok=True)
        rubric_dest.write_text(rubric_path.read_text(encoding="utf-8"), encoding="utf-8")
        written.append(rubric_dest)

    if baseline_path is not None:
        baseline_dest = references_dir / "baseline" / baseline_path.name
        baseline_dest.parent.mkdir(parents=True, exist_ok=True)
        baseline_dest.write_text(baseline_path.read_text(encoding="utf-8"), encoding="utf-8")
        written.append(baseline_dest)

    records = active_frameworks(load_framework_registry(frameworks_dir), domain=domain)

    frameworks_dest_dir = references_dir / "frameworks"
    frameworks_dest_dir.mkdir(parents=True, exist_ok=True)
    index_dest = frameworks_dest_dir / "index.md"
    index_dest.write_text(render_frameworks_index_markdown(records), encoding="utf-8")
    written.append(index_dest)

    # A machine-readable twin of index.md: scripts/assessment.py is
    # stdlib-only and can't parse the source YAML directly, so it reads this
    # JSON rendering instead (see STDLIB_ONLY_MODULES above).
    json_dest = frameworks_dest_dir / "index.json"
    json_dest.write_text(json.dumps(records, indent=2, default=str) + "\n", encoding="utf-8")
    written.append(json_dest)

    for record in records:
        source_file = frameworks_dir / record["file"]
        dest_file = frameworks_dest_dir / record["file"]
        dest_file.parent.mkdir(parents=True, exist_ok=True)
        dest_file.write_text(source_file.read_text(encoding="utf-8"), encoding="utf-8")
        written.append(dest_file)

    return written


def sync_skill_scripts(
    skill_dir: Path, src_dir: Path, modules: list[str] | None = None
) -> list[Path]:
    """Copies every module in *modules* (default STDLIB_ONLY_MODULES) from
    *src_dir* into skill_dir/scripts/, byte-for-byte. Never touches any
    other file in scripts/ (in particular, a hand-authored assessment.py or
    triage.py) — those aren't derived from src/ and this function has no
    opinion about them. Returns every path written.

    *modules* lets a rubric-less, triage-shaped skill (build-plan.md step
    12) exclude rubric.py — a module with nothing for it to parse there —
    rather than carrying a dead file that would suggest the skill scores
    something it doesn't.
    """
    scripts_dir = skill_dir / "scripts"
    scripts_dir.mkdir(parents=True, exist_ok=True)

    written: list[Path] = []
    for module_name in modules or STDLIB_ONLY_MODULES:
        dest = scripts_dir / module_name
        dest.write_text((src_dir / module_name).read_text(encoding="utf-8"), encoding="utf-8")
        written.append(dest)
    return written


def render_family_manifest_markdown(manifest: dict[str, Any]) -> str:
    """Renders family-manifest.yaml as the Markdown the router's SKILL.md
    instructs the model to read (build-plan.md §6.2).
    """
    lines = ["# Skill family manifest", ""]
    for entry in manifest.get("skills", []):
        lines.append(f"## {entry['name']}")
        lines.append("")
        lines.append(f"- **Domain:** {entry['domain']}")
        lines.append(f"- **Status:** {entry['status']}")
        lines.append(f"- **Trigger:** {entry['trigger']}")
        lines.append("")
    return "\n".join(lines)


def sync_router_references(router_dir: Path, family_manifest_path: Path) -> list[Path]:
    """Regenerates router_dir/references/family-manifest.md from
    family_manifest_path. Returns the path written.
    """
    manifest = yaml.safe_load(family_manifest_path.read_text(encoding="utf-8"))
    references_dir = router_dir / "references"
    references_dir.mkdir(parents=True, exist_ok=True)
    dest = references_dir / "family-manifest.md"
    dest.write_text(render_family_manifest_markdown(manifest), encoding="utf-8")
    return [dest]


def sync_all(
    project_root: Path,
    *,
    router_name: str,
    frameworks_dir: Path | None = None,
    rubric_path: Path | None = None,
    src_dir: Path | None = None,
) -> list[Path]:
    """Bulk-syncs every skill listed as `status: built` in
    project_root/family-manifest.yaml — both its references/ and its
    stdlib-only scripts/ — plus the router (named *router_name*) if its
    folder exists. Returns an empty list — without error — if
    family-manifest.yaml doesn't exist yet, matching this project's own
    current state before build sequence step 9.

    Each entry is synced against its own manifest `rubric` field (a
    project-root-relative path), since different domains score against
    different rubrics. Three states are distinguished: an entry with an
    explicit string path syncs that rubric; an entry with no `rubric` key
    at all falls back to *rubric_path* (default project_root/rubric/
    criteria.md), so a manifest written before step 11 (when every skill
    shared one rubric) still works unchanged; an entry with `rubric: null`
    (a triage- or incident-shaped skill, steps 12 and 14) is synced with
    no rubric at all. A `baseline` field (step 16) works the same way but
    with only two states, since no entry predates it: an explicit string
    path syncs that baseline; an absent key means no baseline at all —
    there's no historical default to fall back to.

    Raises ManifestDriftError if a `built` entry has no matching folder
    under .claude/skills/.
    """
    frameworks_dir = frameworks_dir or project_root / "frameworks"
    default_rubric_path = rubric_path or project_root / "rubric" / "criteria.md"
    src_dir = src_dir or project_root / "src" / "privacy_and_ai_governance"
    manifest_path = project_root / "family-manifest.yaml"
    skills_dir = project_root / ".claude" / "skills"

    written: list[Path] = []
    if not manifest_path.exists():
        return written

    manifest = yaml.safe_load(manifest_path.read_text(encoding="utf-8"))
    for entry in manifest.get("skills", []):
        if entry.get("status") != "built":
            continue
        skill_dir = skills_dir / entry["name"]
        if not skill_dir.is_dir():
            raise ManifestDriftError(
                f"family-manifest.yaml lists '{entry['name']}' as built, but "
                f"{skill_dir} does not exist"
            )
        if "rubric" not in entry:
            entry_rubric_path: Path | None = default_rubric_path
        elif entry["rubric"] is None:
            entry_rubric_path = None
        else:
            entry_rubric_path = project_root / entry["rubric"]
        entry_baseline_path = (
            project_root / entry["baseline"] if entry.get("baseline") is not None else None
        )
        written.extend(
            sync_skill_references(
                skill_dir, entry["domain"], frameworks_dir, entry_rubric_path, entry_baseline_path
            )
        )
        scripts_to_sync = ["concision.py", "language.py", "report.py"]
        if entry_rubric_path is not None:
            scripts_to_sync.append("rubric.py")
        if entry_baseline_path is not None:
            scripts_to_sync.append("baseline.py")
        written.extend(sync_skill_scripts(skill_dir, src_dir, scripts_to_sync))

    router_dir = skills_dir / router_name
    if router_dir.is_dir():
        written.extend(sync_router_references(router_dir, manifest_path))

    return written


if __name__ == "__main__":
    root = Path(__file__).resolve().parent.parent
    for path in sync_all(root, router_name="catholic-privacy-and-ai-governance"):
        print(f"synced {path.relative_to(root)}")
